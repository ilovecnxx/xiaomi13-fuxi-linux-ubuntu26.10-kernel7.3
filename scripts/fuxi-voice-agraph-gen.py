#!/usr/bin/env python3
"""fuxi-voice-agraph-gen.py - 把 Android 抓到的 GRAPH_OPEN 带外块生成 C 头文件 (q6voice-agraph.h)。

用法: python3 -I scripts/fuxi-voice-agraph-gen.py <抓包目录> <输出 .h>
抓包目录 = fuxi-gpr-shmdump 的输出 (work/claude-logs/android-voice-shmdump2-20261102)。

每个图生成两份：
  q6voice_agraph_<rx|tx>        原样拷贝（含跨图连线；有的对端模块在 Android 先开的 0x2010/0x2011 里，我们没开）；
  q6voice_agraph_<rx|tx>_strip  去掉对端模块既不在 rx 也不在 tx 块里的 MODULE_CONN / 0x08001061 条目。
另外从块里取出 SUB_GRAPH_CONFIG 的 SG id，供 PREPARE/START/CLOSE 用。
生成时核对: 记录链恰好吃完 size，err 全 0，SG 数与记录一致，否则退出 (宁可不生成)。
块来自 Android 抓包, 仅用于本机语音实验, 不要提交生成的头文件。
"""
import os
import struct
import sys

SG_CFG, MOD_LIST, MOD_CONN, CTRL_LINKS = 0x08001001, 0x08001002, 0x08001004, 0x08001061


def records(data):
    """[(miid, pid, payload)]，假定已由 parse() 核对过。"""
    o, out = 0, []
    while o < len(data):
        miid, pid, sz, _err = struct.unpack_from("<IIII", data, o)
        out.append((miid, pid, data[o + 16:o + 16 + sz]))
        o += 16 + ((sz + 7) & ~7)
    return out


def module_ids(data):
    """MODULE_LIST: {num_lists, [ {sg, cont, num_mods, [ {mid, miid} ] } ] }"""
    ids = set()
    for _m, pid, d in records(data):
        if pid != MOD_LIST:
            continue
        (nl,) = struct.unpack_from("<I", d, 0)
        p = 4
        for _ in range(nl):
            _sg, _c, nm = struct.unpack_from("<III", d, p)
            p += 12
            for _ in range(nm):
                ids.add(struct.unpack_from("<II", d, p)[1])
                p += 8
    return ids


def strip(name, data, known):
    """去掉端点不在 known 里的连线条目，返回 (新块, 去掉的条目描述)。"""
    out, dropped = b"", []
    for miid, pid, d in records(data):
        if pid in (MOD_CONN, CTRL_LINKS):
            (cnt,) = struct.unpack_from("<I", d, 0)
            p, keep = 4, []
            for _ in range(cnt):
                s, sp, t, tp = struct.unpack_from("<4I", d, p)
                end = p + 16
                if pid == CTRL_LINKS:
                    (np_,) = struct.unpack_from("<I", d, end)
                    end += 4
                    for _ in range(np_):
                        _i, psz = struct.unpack_from("<II", d, end)
                        end += 8 + psz
                if s in known and t in known:
                    keep.append(d[p:end])
                else:
                    dropped.append(f"{'CONN' if pid == MOD_CONN else 'CTRL'} {s:x}:{sp:x}>{t:x}:{tp:x}")
                p = end
            if p != len(d):
                raise SystemExit(f"{name}: 连线记录 {pid:#x} 长度不符 ({p:#x} != {len(d):#x})")
            if not keep:
                continue
            d = struct.pack("<I", len(keep)) + b"".join(keep)
        rec = struct.pack("<IIII", miid, pid, len(d), 0) + d
        out += rec + b"\0" * (-len(rec) % 8)
    return out, dropped


# (名字, 来源 GRAPH_OPEN 序号, 来源文件, 偏移, 大小)；偏移/大小来自 GRAPH_OPEN 包的 {lsw, size}
BLOBS = [
    ("rx", 102, "pkt0104-op01001006-map0-7703003000.bin", 0x1000, 0xdf0),
    ("tx", 136, "pkt0138-op01001006-map1-7703003000.bin", 0x1000, 0xdd8),
]


def parse(name, data):
    """返回 (记录数, SG id 列表)。"""
    o = n = 0
    sgs = []
    while o < len(data):
        if o + 16 > len(data):
            raise SystemExit(f"{name}: 尾部不足 16 字节 (offset {o:#x})")
        _miid, pid, sz, err = struct.unpack_from("<IIII", data, o)
        if err != 0:
            raise SystemExit(f"{name}: offset {o:#x} err={err:#x}")
        nxt = o + 16 + ((sz + 7) & ~7)
        if nxt > len(data):
            raise SystemExit(f"{name}: offset {o:#x} size={sz:#x} 超出块长 {len(data):#x}")
        if pid == SG_CFG:
            # { num_sg, [ { sg_id, num_props, props... } ] }
            (cnt,) = struct.unpack_from("<I", data, o + 16)
            p = o + 20
            for _ in range(cnt):
                sg, nprops = struct.unpack_from("<II", data, p)
                p += 8
                for _ in range(nprops):
                    _id, psz = struct.unpack_from("<II", data, p)
                    p += 8 + psz
                sgs.append(sg)
            if p > o + 16 + sz:
                raise SystemExit(f"{name}: SG 记录 offset {o:#x} 越界")
        o = nxt
        n += 1
    return n, sgs


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    lines = [
        "/* SPDX-License-Identifier: GPL-2.0 */",
        "/* Generated by scripts/fuxi-voice-agraph-gen.py from an Android capture. Do not edit.",
        " * Raw GRAPH_OPEN payloads; for the fuxi voice experiment only, not in git. */",
        "",
    ]
    blobs = {}
    for name, pkt, fn, off, size in BLOBS:
        with open(os.path.join(src, fn), "rb") as f:
            buf = f.read()
        data = buf[off:off + size]
        if len(data) != size:
            raise SystemExit(f"{name}: {fn} 只有 {len(buf):#x} 字节, 取不到 {off:#x}+{size:#x}")
        blobs[name] = (pkt, data)
    known = set().union(*(module_ids(d) for _p, d in blobs.values()))

    def emit(var, data, comment):
        lines.append(f"/* {comment} */")
        lines.append(f"static const u8 {var}[] __aligned(8) = {{")
        for i in range(0, len(data), 16):
            lines.append("\t" + " ".join(f"0x{b:02x}," for b in data[i:i + 16]))
        lines.append("};")
        lines.append("")

    for name, (pkt, data) in blobs.items():
        nrec, sgs = parse(name, data)
        if not sgs:
            raise SystemExit(f"{name}: 没有 SUB_GRAPH_CONFIG")
        print(f"{name}: GRAPH_OPEN #{pkt} size={len(data):#x} records={nrec} sgs=" +
              ",".join(f"{s:#x}" for s in sgs))
        sdata, dropped = strip(name, data, known)
        snrec, ssgs = parse(name + "_strip", sdata)
        if ssgs != sgs:
            raise SystemExit(f"{name}_strip: SG 列表变了")
        print(f"{name}_strip: size={len(sdata):#x} records={snrec} dropped={len(dropped)}: " +
              ", ".join(dropped))
        lines.append(f"static const u32 q6voice_agraph_{name}_sgs[] = {{ " +
                     ", ".join(f"0x{s:08x}" for s in sgs) + " };")
        emit(f"q6voice_agraph_{name}", data, f"GRAPH_OPEN #{pkt}, {nrec} records, as captured")
        emit(f"q6voice_agraph_{name}_strip", sdata,
             f"GRAPH_OPEN #{pkt}, {snrec} records, {len(dropped)} links to unknown modules dropped")
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
