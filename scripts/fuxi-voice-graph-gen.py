#!/usr/bin/env python3
"""fuxi-voice-graph-gen.py - 把 fuxi-acdb-dump.py 的 graph --json --no-cal 输出转成内核用的 C 表。

用法（python3 -I，输入文件放在别的目录）:
  python3 -I scripts/fuxi-voice-graph-gen.py TX.json RX.json > q6voice-graphs.h
只输出图内连线；端点在图外的连线（回声参考等）写成注释，不下发。
"""
import json
import sys


def prop(props, prefix):
    for k, v in props:
        if k.startswith(prefix):
            return v
    raise KeyError(prefix)


def emit(name, path):
    j = json.load(open(path))
    sgs, conts, mods, conns, ext = [], [], [], [], []
    seen_conn = set()
    for si, s in enumerate(j['sgs']):
        sid = int(s['sg'], 16)
        sc = s['sgcfg']
        sgs.append((sid, prop(sc, 'perf')[0], prop(sc, 'dir')[0], prop(sc, 'scenario')[0]))
        props = {int(m): p for m, p in s['modprops'].items()}
        for ml, c in zip(s['modlist'], s['containers']):
            assert ml['cont'] == c['id'], (ml['cont'], c['id'])
            ci = len(conts)
            cp = c['props']
            conts.append((c['id'], prop(cp, 'cap_list')[1], prop(cp, 'graph_pos')[0],
                          prop(cp, 'stack_size')[0], prop(cp, 'proc_domain')[0], si))
            for m in ml['mods']:
                ip, op = props[m['miid']][0][1]
                mods.append((m['mid'], m['miid'], ip, op, ci))
        for c in s['conns']:
            t = (c['src_miid'], c['src_port'], c['dst_miid'], c['dst_port'])
            if t in seen_conn:
                continue
            seen_conn.add(t)
            (conns if c['src_in_graph'] and c['dst_in_graph'] else ext).append(t)
    o = ['/* ---- %s: alias %s %s ---- */' % (name, j['alias_id'], j['name'])]
    o.append('static const struct q6voice_sg %s_sgs[] = {' % name)
    o += ['\t{ 0x%x, %d, %d, %d },' % x for x in sgs] + ['};']
    o.append('static const struct q6voice_cont %s_conts[] = {' % name)
    o += ['\t{ 0x%x, 0x%x, %d, %d, %d, %d },' % x for x in conts] + ['};']
    o.append('static const struct q6voice_mod %s_mods[] = {' % name)
    o += ['\t{ 0x%x, 0x%x, %d, %d, %d },' % x for x in mods] + ['};']
    o.append('static const struct q6voice_conn %s_conns[] = {' % name)
    o += ['\t{ 0x%x, %d, 0x%x, %d },' % x for x in conns] + ['};']
    o.append('/* graph-external connections, NOT sent: %s */' %
             ', '.join('%x:%d>%x:%d' % x for x in ext))
    o.append('')
    return o


def main():
    out = ['/* SPDX-License-Identifier: GPL-2.0 */',
           '/* Generated by scripts/fuxi-voice-graph-gen.py from ACDB. Do not edit. */', '']
    out += emit('q6voice_tx', sys.argv[1])
    out += emit('q6voice_rx', sys.argv[2])
    print('\n'.join(out))


main()
