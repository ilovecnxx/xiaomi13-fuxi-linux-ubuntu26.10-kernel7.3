#!/usr/bin/env python3
"""fuxi-voice-graph-x162-gen.py - 从 ACDB graph --json --no-cal 输出生成 VCPM 注册与控制链路表。

用法（python3 -I，输入文件放在别的目录）:
  python3 -I scripts/fuxi-voice-graph-x162-gen.py TX.json RX.json > q6voice-ctrl.h
对图里每个 SG 输出 ACDB 原样的:
  - 0x08001162 / 0x080011b2 的 {vcpm_param, miid} 对（发给 VCPM，miid 4）
  - 0x08001061 控制链路 {src, src_port, dst, dst_port, intent}（发给 APM）
依据：Android 的 GRAPH_OPEN 逐 SG 发这两类记录，内容与 ACDB 一致（设计文档 §7g）。
"""
import json
import sys

X162_INNER = 0x080011b2
CTRL_INTENT = 0x08001062
CTRL_FLAG = 0x0800136f


def emit(name, path):
    j = json.load(open(path))
    x162, ctrl = [], []
    for s in j['sgs']:
        sg = int(s['sg'], 16)
        for e in s.get('x162_unparsed') or []:
            if e['sg'] != sg:
                sys.exit('x162 sg mismatch %x %x' % (e['sg'], sg))
            for pid, pairs in e['props']:
                if int(pid, 16) != X162_INNER:
                    sys.exit('unexpected x162 prop %s in sg %x' % (pid, sg))
                for vp, mi in pairs:
                    x162.append((sg, int(vp, 16), int(mi, 16)))
        for c in s['ctrl_links']:
            props = {int(p, 16): v for p, v in c['props']}
            if set(props) != {CTRL_INTENT, CTRL_FLAG} or props[CTRL_INTENT][0] != 1 or props[CTRL_FLAG] != [1]:
                sys.exit('unexpected ctrl props %s in sg %x' % (c['props'], sg))
            ctrl.append((sg, c['src'], c['src_port'], c['dst'], c['dst_port'], props[CTRL_INTENT][1]))
    o = ['/* ---- %s: alias %s ---- */' % (name, j['alias_id'])]
    o.append('static const struct q6voice_x162 %s_x162[] = {' % name)
    o += ['\t{ 0x%x, 0x%x, 0x%x },' % x for x in x162] + ['};']
    o.append('static const struct q6voice_ctrl %s_ctrl[] = {' % name)
    o += ['\t{ 0x%x, 0x%x, 0x%x, 0x%x, 0x%x, 0x%x },' % x for x in ctrl] + ['};']
    o.append('')
    return o


def main():
    out = ['/* SPDX-License-Identifier: GPL-2.0 */',
           '/* Generated by scripts/fuxi-voice-graph-x162-gen.py from ACDB. Do not edit. */',
           '/* x162: { sg, vcpm_param_id, miid }   ctrl: { sg, src, src_port, dst, dst_port, intent } */', '']
    out += emit('q6voice_tx', sys.argv[1])
    out += emit('q6voice_rx', sys.argv[2])
    print('\n'.join(out))


main()
